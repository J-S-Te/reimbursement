CREATE TABLE IF NOT EXISTS exp_archive_borrow (
 id VARCHAR(64) NOT NULL PRIMARY KEY,
 tenant_id VARCHAR(64) NOT NULL,
 archive_id VARCHAR(64) NOT NULL,
 claim_id VARCHAR(64) NOT NULL,
 archive_version BIGINT NOT NULL,
 manifest_hash VARCHAR(64) NOT NULL,
 requester VARCHAR(128) NOT NULL,
 requester_tenant_all BOOLEAN NOT NULL DEFAULT FALSE,
 reason VARCHAR(2000) NOT NULL,
 requested_days INT NOT NULL,
 status VARCHAR(20) NOT NULL,
 version BIGINT NOT NULL,
 approver VARCHAR(128) NULL,
 decision_reason VARCHAR(2000) NULL,
 job_id VARCHAR(64) NULL,
 approved_at DATETIME(3) NULL,
 expires_at DATETIME(3) NULL,
 created_at DATETIME(3) NULL,
 updated_at DATETIME(3) NULL,
 KEY idx_archive_borrow_inbox (tenant_id,requester,status),
 KEY idx_archive_borrow_archive (archive_id),
 KEY idx_archive_borrow_claim (claim_id),
 KEY idx_archive_borrow_job (job_id),
 KEY idx_archive_borrow_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
